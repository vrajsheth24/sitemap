import React, { useMemo, useState } from 'react';
import { Plus, Trash2, Download } from 'lucide-react';
import { downloadText } from '../../utils/seoTools';
import { CodeOutput } from './ToolShared';

const COMMON_PATHS = ['/admin/', '/wp-admin/', '/cart/', '/checkout/', '/account/', '/search', '/*?sort=', '/tmp/'];

const AI_CRAWLERS = [
  { token: 'GPTBot', owner: 'OpenAI' },
  { token: 'ChatGPT-User', owner: 'OpenAI' },
  { token: 'ClaudeBot', owner: 'Anthropic' },
  { token: 'anthropic-ai', owner: 'Anthropic' },
  { token: 'Google-Extended', owner: 'Google (Gemini training)' },
  { token: 'CCBot', owner: 'Common Crawl' },
  { token: 'PerplexityBot', owner: 'Perplexity' },
  { token: 'Bytespider', owner: 'ByteDance' },
  { token: 'meta-externalagent', owner: 'Meta' }
];

const BOT_OPTIONS = ['Googlebot', 'Googlebot-Image', 'Bingbot', 'DuckDuckBot', 'YandexBot', 'Baiduspider', 'AhrefsBot', 'SemrushBot', 'MJ12bot'];

const toLines = (text) => text.split(/\r?\n/).map(l => l.trim()).filter(Boolean);

export default function RobotsGeneratorTool({ pages, targetUrl, addToast }) {
  const origin = (() => {
    try { return new URL(targetUrl || pages[0]?.url).origin; } catch (e) { return 'https://example.com'; }
  })();

  const [defaultPolicy, setDefaultPolicy] = useState('allow');
  const [disallow, setDisallow] = useState('/admin/\n/cart/');
  const [allow, setAllow] = useState('');
  const [crawlDelay, setCrawlDelay] = useState('');
  const [blockedAi, setBlockedAi] = useState({});
  const [botRules, setBotRules] = useState([]);
  const [sitemaps, setSitemaps] = useState(`${origin}/sitemap.xml`);

  const addPath = (path) => {
    if (toLines(disallow).includes(path)) return;
    setDisallow(prev => (prev.trim() ? `${prev.trim()}\n${path}` : path));
  };

  const allAiBlocked = AI_CRAWLERS.every(b => blockedAi[b.token]);

  const output = useMemo(() => {
    const out = ['# robots.txt generated by SitemapFlow', ''];

    out.push('User-agent: *');
    if (defaultPolicy === 'block') {
      out.push('Disallow: /');
    } else {
      const d = toLines(disallow);
      const a = toLines(allow);
      if (d.length === 0 && a.length === 0) out.push('Disallow:');
      a.forEach(p => out.push(`Allow: ${p}`));
      d.forEach(p => out.push(`Disallow: ${p}`));
    }
    if (crawlDelay) out.push(`Crawl-delay: ${crawlDelay}`);

    botRules.filter(r => r.agent.trim()).forEach(rule => {
      out.push('', `User-agent: ${rule.agent.trim()}`);
      if (rule.mode === 'block') {
        out.push('Disallow: /');
      } else if (rule.mode === 'allow') {
        out.push('Allow: /');
      } else {
        const paths = toLines(rule.paths);
        if (paths.length === 0) out.push('Disallow:');
        paths.forEach(p => out.push(`Disallow: ${p}`));
      }
    });

    const ai = AI_CRAWLERS.filter(b => blockedAi[b.token]);
    if (ai.length) {
      out.push('', '# AI crawlers');
      ai.forEach(b => out.push(`User-agent: ${b.token}`));
      out.push('Disallow: /');
    }

    const maps = toLines(sitemaps);
    if (maps.length) {
      out.push('');
      maps.forEach(m => out.push(`Sitemap: ${m}`));
    }
    return out.join('\n') + '\n';
  }, [defaultPolicy, disallow, allow, crawlDelay, botRules, blockedAi, sitemaps]);

  const updateRule = (i, patch) => setBotRules(rules => rules.map((r, j) => (j === i ? { ...r, ...patch } : r)));

  return (
    <div className="tool-body">
      <div className="tool-columns">
        <div className="glass-panel tool-panel">
          <h3 className="tool-panel-title">All crawlers (User-agent: *)</h3>
          <div className="segmented" style={{ alignSelf: 'flex-start' }}>
            <button type="button" className={defaultPolicy === 'allow' ? 'active' : ''} onClick={() => setDefaultPolicy('allow')}>Allow, with exceptions</button>
            <button type="button" className={defaultPolicy === 'block' ? 'active' : ''} onClick={() => setDefaultPolicy('block')}>Block entire site</button>
          </div>

          {defaultPolicy === 'block' ? (
            <span className="option-hint" style={{ color: 'var(--accent-red)' }}>
              Every compliant crawler, including Google, will stop crawling this site. Use this only for staging or private sites.
            </span>
          ) : (
            <>
              <div className="option-group">
                <label className="option-label" htmlFor="rg-disallow">Disallow paths (one per line)</label>
                <textarea id="rg-disallow" rows="4" className="code-textarea" value={disallow} onChange={(e) => setDisallow(e.target.value)} spellCheck={false} />
                <div style={{ display: 'flex', gap: '0.35rem', flexWrap: 'wrap' }}>
                  {COMMON_PATHS.map(p => (
                    <button key={p} type="button" className="preset-chip" onClick={() => addPath(p)}>+ {p}</button>
                  ))}
                </div>
              </div>
              <div className="option-group">
                <label className="option-label" htmlFor="rg-allow">Allow paths (exceptions inside disallowed folders)</label>
                <textarea id="rg-allow" rows="2" className="code-textarea" value={allow} onChange={(e) => setAllow(e.target.value)} placeholder="/admin/public/" spellCheck={false} />
              </div>
            </>
          )}

          <div className="form-grid">
            <div className="option-group">
              <label className="option-label" htmlFor="rg-delay">Crawl-delay (seconds)</label>
              <input id="rg-delay" type="number" min="0" max="60" className="option-input" value={crawlDelay}
                onChange={(e) => setCrawlDelay(e.target.value === '' ? '' : String(Math.max(0, Math.min(60, parseInt(e.target.value, 10) || 0))))} placeholder="none" />
              <span className="option-hint">Bing and Yandex honor this; Google ignores it.</span>
            </div>
          </div>

          <div className="option-group">
            <label className="option-label" htmlFor="rg-sitemaps">Sitemap URLs (one per line)</label>
            <textarea id="rg-sitemaps" rows="2" className="code-textarea" value={sitemaps} onChange={(e) => setSitemaps(e.target.value)} spellCheck={false} />
          </div>
        </div>

        <div style={{ display: 'flex', flexDirection: 'column', gap: '1rem', minWidth: 0 }}>
          <div className="glass-panel tool-panel">
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', gap: '0.5rem', flexWrap: 'wrap' }}>
              <h3 className="tool-panel-title">AI crawlers</h3>
              <button type="button" className="link-btn" onClick={() => setBlockedAi(allAiBlocked ? {} : Object.fromEntries(AI_CRAWLERS.map(b => [b.token, true])))}>
                {allAiBlocked ? 'Allow all' : 'Block all'}
              </button>
            </div>
            <span className="option-hint">Block bots that collect content for AI training or AI answers. This doesn't affect normal Google or Bing search.</span>
            <div className="options-toggles-row" style={{ borderTop: 'none', paddingTop: 0 }}>
              {AI_CRAWLERS.map(b => (
                <label key={b.token} className="toggle-control">
                  <input type="checkbox" checked={!!blockedAi[b.token]} onChange={() => setBlockedAi(prev => ({ ...prev, [b.token]: !prev[b.token] }))} />
                  <span><code>{b.token}</code> <span className="text-muted">{b.owner}</span></span>
                </label>
              ))}
            </div>
          </div>

          <div className="glass-panel tool-panel">
            <h3 className="tool-panel-title">Rules for specific bots</h3>
            {botRules.length === 0 && <span className="option-hint">Optional — e.g. block SEO tool crawlers like AhrefsBot to save bandwidth.</span>}
            {botRules.map((rule, i) => (
              <div key={i} className="subpanel">
                <div style={{ display: 'flex', gap: '0.4rem', alignItems: 'center', flexWrap: 'wrap' }}>
                  <input className="option-input" list="rg-bots" style={{ flex: '1 1 140px' }} placeholder="Bot name" value={rule.agent}
                    onChange={(e) => updateRule(i, { agent: e.target.value })} aria-label="Bot user-agent" />
                  <select className="option-select" value={rule.mode} onChange={(e) => updateRule(i, { mode: e.target.value })} aria-label="Rule">
                    <option value="block">Block everything</option>
                    <option value="paths">Block some paths</option>
                    <option value="allow">Allow everything</option>
                  </select>
                  <button type="button" className="icon-btn hover-danger" aria-label="Remove rule" onClick={() => setBotRules(rules => rules.filter((_, j) => j !== i))}>
                    <Trash2 size={13} />
                  </button>
                </div>
                {rule.mode === 'paths' && (
                  <textarea rows="2" className="code-textarea" placeholder="/private/" value={rule.paths} spellCheck={false}
                    onChange={(e) => updateRule(i, { paths: e.target.value })} aria-label="Paths to block" />
                )}
              </div>
            ))}
            <datalist id="rg-bots">
              {BOT_OPTIONS.map(b => <option key={b} value={b} />)}
            </datalist>
            <button type="button" className="btn btn-secondary" style={{ alignSelf: 'flex-start' }}
              onClick={() => setBotRules(rules => [...rules, { agent: '', mode: 'block', paths: '' }])}>
              <Plus size={14} /><span>Add bot rule</span>
            </button>
          </div>
        </div>
      </div>

      <CodeOutput code={output} filename="robots.txt" addToast={addToast} />
      <button type="button" className="btn btn-primary" style={{ alignSelf: 'flex-start' }}
        onClick={() => { downloadText(output, 'robots.txt'); addToast('Downloaded robots.txt', 'success'); }}>
        <Download size={14} /><span>Download robots.txt</span>
      </button>
    </div>
  );
}
